/**
 * Render context — everything the renderer and the field resolver need, supplied
 * by the caller. Deliberately hook-free: the renderer must be usable inside a
 * hidden print portal, inside a designer canvas, and 4-up in a bulk grid, so
 * context (timezone formatter, attributes, company profile) is passed in rather
 * than pulled from React context inside the render tree.
 */

import type { DyeingPrintData } from './dyeingPrintData';

export interface PrintContext {
    /** Kartu Kerja only — null on every other document. */
    workOrder: any;
    parentMO: any;
    /**
     * The record a non-WO document prints (a shipment's Surat Jalan, ...), already
     * shaped by that doc type's builder. Its own resolver reads it (see docs/).
     */
    doc?: any;
    /** Absolute URL of the company logo, when the profile has one. */
    companyLogoUrl?: string;
    /** Pre-generated QR data URL. Generated by the caller so bulk print does it once per WO. */
    qrDataUrl?: string;
    companyName?: string;
    /** Free-text department typed at print time. */
    department?: string;
    /** Already-formatted "today" string. */
    printDate: string;
    /** Timezone-aware date formatter for record dates. */
    formatDate: (iso: string) => string;
    /** Resolve a system attribute value carried by the MO, by system_role. */
    moAttributeValue: (systemRole: string) => string;
    /**
     * Bath + weighed doses for a dyeing card, fetched by the print surface (see
     * dyeingPrintData.ts). Absent for every other work centre type, and for a
     * dyeing WO whose run or dose calc could not be loaded — the doses band hides
     * itself rather than printing an empty table.
     */
    dyeing?: DyeingPrintData | null;
}

export interface BuildContextArgs {
    workOrder: any;
    parentMO: any;
    qrDataUrl?: string;
    companyName?: string;
    companyLogoUrl?: string;
    department?: string;
    attributes?: any[];
    /** TimezoneContext's `formatCustom`. */
    tzFormatCustom: (iso: string, opts: Intl.DateTimeFormatOptions, locale?: string) => string;
    dyeing?: DyeingPrintData | null;
}

const SHORT_DATE: Intl.DateTimeFormatOptions = { day: '2-digit', month: '2-digit', year: '2-digit' };

/**
 * Assemble a PrintContext. The attribute lookup mirrors the old weaving card:
 * find the system attribute by `system_role`, then the value the MO carries in
 * `attribute_value_ids`.
 */
export function buildPrintContext({
    workOrder, parentMO, qrDataUrl, companyName, companyLogoUrl, department, attributes = [], tzFormatCustom,
    dyeing = null,
}: BuildContextArgs): PrintContext {
    const moValueIds: string[] = parentMO?.attribute_value_ids || [];

    const moAttributeValue = (systemRole: string): string => {
        const attr = (attributes || []).find(
            (a: any) => (a.system_role || '').toLowerCase() === systemRole.toLowerCase()
        );
        const value = attr?.values?.find((v: any) => moValueIds.includes(v.id));
        return value?.value || '';
    };

    return {
        workOrder,
        parentMO,
        qrDataUrl,
        companyName,
        companyLogoUrl,
        department,
        printDate: new Date().toLocaleDateString('id-ID', { day: '2-digit', month: '2-digit', year: 'numeric' }),
        formatDate: (iso: string) => tzFormatCustom(iso, SHORT_DATE, 'id-ID'),
        moAttributeValue,
        dyeing,
    };
}
